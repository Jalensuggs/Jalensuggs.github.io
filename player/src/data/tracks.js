// 辅助：为纯文本歌词自动生成均匀时间轴
// start: 开始秒数, interval: 每行间隔秒数
// ============================================================
function makeLyrics(lines, start = 12, interval = 4) {
  return lines
    .map(l => l.trim())
    .filter(l => l.length > 0)
    .map((text, i) => ({ time: start + i * interval, text }));
}

